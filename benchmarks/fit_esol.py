"""Fit the ESOL solubility regression on this package's own descriptors.

Delaney's ESOL model predicts log aqueous solubility from four descriptors:
clogP, molecular weight, rotatable-bond count and aromatic proportion. His
published coefficients assume his clogP; NEXUS computes a Crippen-style logP of
its own, fitted separately against logD, which sits on a different scale. Using
the published coefficients unchanged against this logP leaves a +0.78 log-unit
bias and an RMSE of 1.66 on ESOL, so the form is kept and the four coefficients
are re-estimated here on a scaffold split, held-out accuracy reported.

    python -m benchmarks.fit_esol
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from nexus.chem.admet import aromatic_proportion
from nexus.chem.descriptors import crippen_logp, num_rotatable_bonds
from nexus.chem.scaffold import scaffold_split

ROOT = Path(__file__).resolve().parent.parent
RIDGE = 1e-3

# Delaney (2004), J. Chem. Inf. Comput. Sci. 44, 1000, Table 3: the published
# fit, kept here so the refit is always reported against it rather than
# replacing it silently.
DELANEY = np.array([-0.63, -0.0062, 0.066, -0.74, 0.16])


def design_matrix(mols) -> np.ndarray:
    """ESOL's four descriptors plus an intercept column."""
    X = np.ones((len(mols), 5))
    for row, mol in enumerate(mols):
        X[row, 0] = crippen_logp(mol)
        X[row, 1] = mol.molecular_weight()
        X[row, 2] = num_rotatable_bonds(mol)
        X[row, 3] = aromatic_proportion(mol)
    return X


def metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    resid = y_pred - y_true
    ss_res = float(np.sum(resid ** 2))
    ss_tot = float(np.sum((y_true - y_true.mean()) ** 2))
    return {
        "n": int(len(y_true)),
        "mae": float(np.mean(np.abs(resid))),
        "rmse": float(np.sqrt(np.mean(resid ** 2))),
        "r2": float(1 - ss_res / ss_tot) if ss_tot > 0 else float("nan"),
        "bias": float(np.mean(resid)),
        "pearson_r": float(np.corrcoef(y_true, y_pred)[0, 1]),
    }


def main() -> None:
    from nexus.data import load_dataset

    mols, Y, _, _ = load_dataset("esol")
    y = Y[:, 0]
    keep = np.isfinite(y)
    mols = [m for m, k in zip(mols, keep) if k]
    y = y[keep]

    train, valid, test = scaffold_split(mols)
    train = np.concatenate([train, valid])
    X = design_matrix(mols)

    A = X[train]
    reg = RIDGE * np.eye(A.shape[1])
    reg[-1, -1] = 0.0                      # do not penalise the intercept
    beta = np.linalg.solve(A.T @ A + reg, A.T @ y[train])

    report = {
        "dataset": "ESOL / Delaney (measured log aqueous solubility, mol/L)",
        "n_molecules": int(len(mols)),
        "split": "scaffold (train+valid vs held-out test)",
        "ridge_lambda": RIDGE,
        "coefficients": {
            "logp": float(beta[0]), "mw": float(beta[1]),
            "rotatable_bonds": float(beta[2]), "aromatic_proportion": float(beta[3]),
            "intercept": float(beta[4]),
        },
        "train": metrics(y[train], X[train] @ beta),
        "test": metrics(y[test], X[test] @ beta),
        "delaney_published_coefficients_on_test": metrics(y[test], X[test] @ DELANEY),
        "baseline_predict_mean": metrics(y[test], np.full(len(test), y[train].mean())),
    }

    out = ROOT / "nexus" / "chem" / "admet_params.py"
    lines = [
        '"""Fitted coefficients for the ESOL solubility regression.',
        "",
        "Generated by benchmarks/fit_esol.py -- do not edit by hand.",
        f"Delaney's four-descriptor form, re-estimated on {report['n_molecules']} compounds",
        "with measured log aqueous solubility (ESOL), scaffold split.",
        f"Held-out test RMSE {report['test']['rmse']:.3f}, R^2 {report['test']['r2']:.3f}.",
        '"""',
        "",
        f"ESOL_LOGP = {float(beta[0]):.6f}",
        f"ESOL_MW = {float(beta[1]):.6f}",
        f"ESOL_ROTATABLE_BONDS = {float(beta[2]):.6f}",
        f"ESOL_AROMATIC_PROPORTION = {float(beta[3]):.6f}",
        f"ESOL_INTERCEPT = {float(beta[4]):.6f}",
        "",
        f"ESOL_TEST_RMSE = {report['test']['rmse']:.3f}",
        f"ESOL_TEST_R2 = {report['test']['r2']:.3f}",
    ]
    out.write_text("\n".join(lines) + "\n")

    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "esol_fit.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
