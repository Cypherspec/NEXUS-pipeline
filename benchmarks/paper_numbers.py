"""Emit every number the paper quotes as a LaTeX macro, read from results/.

Nothing in the paper is typed by hand: each \\newcommand here is computed from
a file in results/, so a stale figure and a stale sentence cannot disagree. A
macro whose result file is missing expands to a visible placeholder rather than
to a plausible-looking number.

    python -m benchmarks.paper_numbers
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
OUT = ROOT / "paper" / "numbers.tex"

MISSING = r"\textbf{??}"


def load(name: str):
    path = RESULTS / name
    return json.loads(path.read_text()) if path.exists() else None


def macro(name: str, value) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def ident(*parts: str) -> str:
    """A legal LaTeX command name: letters only, words capitalised.

    Method names carry +, - and spaces ("ecfp+descriptors+rf"), none of which
    may appear in a control sequence.
    """
    words: list[str] = []
    for part in parts:
        token = ""
        for ch in str(part):
            if ch.isalpha():
                token += ch
            else:
                if token:
                    words.append(token)
                token = ""
        if token:
            words.append(token)
    if not words:
        return "unnamed"
    return words[0][0].lower() + words[0][1:] + "".join(w.capitalize() for w in words[1:])


def pct(x, digits: int = 1) -> str:
    return MISSING if x is None else f"{100 * float(x):.{digits}f}\\%"


def num(x, digits: int = 2) -> str:
    return MISSING if x is None else f"{float(x):.{digits}f}"


def dig(x) -> str:
    return MISSING if x is None else f"{int(x):,}".replace(",", "{,}")


def code_stats() -> tuple[int, int]:
    """Lines of library code and of tests."""
    def count(folder: str) -> int:
        total = 0
        for path in (ROOT / folder).rglob("*.py"):
            if "__pycache__" in str(path):
                continue
            total += len(path.read_text().splitlines())
        return total
    return count("nexus"), count("tests")


def n_tests() -> str:
    try:
        out = subprocess.run(["python3", "-m", "pytest", "tests/", "--collect-only", "-q"],
                             cwd=ROOT, capture_output=True, text=True, timeout=300)
        for line in reversed(out.stdout.splitlines()):
            if "test" in line and line.strip().split("/")[0].strip().isdigit():
                return line.strip().split()[0]
            if line.strip().endswith("tests collected") or " tests collected" in line:
                return line.strip().split()[0]
    except Exception:                                  # noqa: BLE001
        pass
    return MISSING


def main() -> None:
    lines = ["% Generated by benchmarks/paper_numbers.py -- do not edit.",
             "% Every value is read from results/; regenerate after any new run."]

    lib, tests = code_stats()
    lines += [macro("codeLines", dig(lib)), macro("testLines", dig(tests)),
              macro("nTests", n_tests())]

    # --- MoleculeNet
    molnet = load("molnet_summary.json")
    if molnet:
        datasets = molnet.get("datasets", molnet)
        for name, block in datasets.items():
            if not isinstance(block, dict):
                continue
            methods = block.get("methods", block)
            for method, stats in methods.items():
                if not isinstance(stats, dict) or "mean" not in stats:
                    continue
                lines.append(macro(ident("molnet", name, method),
                                   num(stats["mean"], 3)))

    # --- Affinity
    affinity = load("affinity.json")
    if affinity:
        lines.append(macro("affinityPairs", dig(affinity.get("n_pairs"))))
        lines.append(macro("affinityDrugs", dig(affinity.get("n_drugs"))))
        lines.append(macro("affinityTargets", dig(affinity.get("n_targets"))))
        for split, skey in (("random", "Random"), ("cold-drug", "ColdDrug"),
                            ("cold-target", "ColdTarget")):
            block = affinity.get("splits", {}).get(split, {})
            best = block.get("random forest", {})
            lines.append(macro(ident("affinity", skey, "ci"), num(best.get("ci", {}).get("mean"), 3)))
            lines.append(macro(ident("affinity", skey, "pearson"),
                               num(best.get("pearson", {}).get("mean"), 3)))
            lines.append(macro(ident("affinity", skey, "rmse"),
                               num(best.get("rmse", {}).get("mean"), 3)))

    # --- Conformal, adaptive vs constant width
    conf = load("conformal_adaptive.json")
    if conf:
        lines.append(macro("conformalNominal", pct(conf.get("nominal_coverage"), 0)))
        lines.append(macro("conformalSeeds", conf.get("seeds", MISSING)))
        for name, variants in conf.get("datasets", {}).items():
            for key, short in (("standard", "Std"), ("gp_sigma", "Sigma"),
                               ("residual_fitted", "Resid")):
                entry = variants.get(key)
                if not entry:
                    continue
                stem = ident("conf", name, short)
                lines += [macro(stem + "Cov", num(entry["coverage"], 3)),
                          macro(stem + "Width", num(entry["mean_width"], 2)),
                          macro(stem + "Spread", num(entry["conditional_spread"], 3)),
                          macro(stem + "Worst", num(entry["worst_quintile_coverage"], 3))]

    # --- Generation
    gen = load("generation.json")
    if gen:
        lines += [macro("genTrainMolecules", dig(gen.get("n_training_molecules"))),
                  macro("genSteps", dig(gen.get("training_steps"))),
                  macro("genDiffusionSteps", dig(gen.get("diffusion_steps"))),
                  macro("genClassBalance", num(gen.get("class_balance"), 1)),
                  macro("genBondWeight", num(gen.get("bond_weight"), 1)),
                  macro("genTrainDegree", num(gen.get("training_mean_degree"), 2))]
        for key, short in (("model", "Model"),
                           ("model_unconstrained_sampling", "Unconstrained"),
                           ("marginal_baseline", "Baseline")):
            block = gen.get(key, {})
            if not block:
                continue
            lines += [macro(ident("gen", short, "validity"), pct(block.get("validity"))),
                      macro(ident("gen", short, "fragment"), pct(block.get("validity_largest_fragment"))),
                      macro(ident("gen", short, "degree"), num(block.get("mean_degree"), 2)),
                      macro(ident("gen", short, "unique"), pct(block.get("uniqueness"))),
                      macro(ident("gen", short, "novel"), pct(block.get("novelty")))]
        rej = gen.get("model", {}).get("rejections", {})
        total = gen.get("model", {}).get("n_sampled") or 1
        lines.append(macro("genDisconnectedShare",
                           pct(rej.get("disconnected", 0) / total)))
        lines.append(macro("genValenceShare", pct(rej.get("valence", 0) / total)))

    # --- Descriptors, GO, active learning, free energy
    desc = load("descriptor_validation.json")
    if desc:
        exact, n = [], 0
        for block in desc.values():
            for col, s in block.get("descriptors", {}).items():
                if col == "_all":
                    continue
                exact.append(s["fraction_exact"])
                n += s["n"]
        if exact:
            lines += [macro("descriptorBest", pct(max(exact))),
                      macro("descriptorMolecules", dig(n))]

    go = load("go_validation.json")
    if go:
        lines.append(macro("goTerms", dig(go.get("n_terms"))))
        lines.append(macro("goAnnotations", dig(go.get("n_annotations"))))
        fp = go.get("false_positive_control", {})
        lines += [macro("goFpTrials", dig(fp.get("n_trials"))),
                  macro("goFpGenes", dig(fp.get("genes_per_trial"))),
                  macro("goFpMeanTerms", num(fp.get("mean_significant_terms"), 2)),
                  macro("goFpAnyHit", pct(fp.get("fraction_trials_with_any_hit")))]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    missing = sum(1 for line in lines if MISSING in line)
    print(f"wrote {OUT.relative_to(ROOT)} with {len(lines) - 2} macros"
          + (f", {missing} still missing a result file" if missing else ""))


if __name__ == "__main__":
    main()
