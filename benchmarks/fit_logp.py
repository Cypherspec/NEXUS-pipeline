"""Fit the atom-contribution logP model on experimental data.

Uses the MoleculeNet Lipophilicity set (4,200 compounds, experimental
octanol/water logD at pH 7.4 from ChEMBL). Contributions are least-squares
estimates on a scaffold-split training set; held-out accuracy is reported and
written to results/logp_fit.json so the model's quality is never assumed.

    python -m benchmarks.fit_logp
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from nexus.chem.descriptors import crippen_atom_type
from nexus.chem.scaffold import scaffold_split

ROOT = Path(__file__).resolve().parent.parent
RIDGE = 1.0


def design_matrix(mols, types: list[str]) -> np.ndarray:
    index = {t: k for k, t in enumerate(types)}
    X = np.zeros((len(mols), len(types) + 2))
    for row, mol in enumerate(mols):
        for i in range(mol.n_atoms):
            t = crippen_atom_type(mol, i)
            if t in index:
                X[row, index[t]] += 1
            X[row, -2] += mol.atoms[i].total_h
        X[row, -1] = 1.0            # intercept
    return X


def metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    resid = y_pred - y_true
    ss_res = float(np.sum(resid ** 2))
    ss_tot = float(np.sum((y_true - y_true.mean()) ** 2))
    return {
        "n": int(len(y_true)),
        "mae": float(np.mean(np.abs(resid))),
        "rmse": float(np.sqrt(np.mean(resid ** 2))),
        "r2": float(1 - ss_res / ss_tot) if ss_tot > 0 else float("nan"),
        "pearson_r": float(np.corrcoef(y_true, y_pred)[0, 1]),
    }


def main() -> None:
    from nexus.data import load_dataset

    mols, Y, spec, _ = load_dataset("lipo")
    y = Y[:, 0]
    keep = np.isfinite(y)
    mols = [m for m, k in zip(mols, keep) if k]
    y = y[keep]

    train, valid, test = scaffold_split(mols)
    train = np.concatenate([train, valid])
    types = sorted({crippen_atom_type(m, i) for m in mols for i in range(m.n_atoms)})
    X = design_matrix(mols, types)

    A = X[train]
    reg = RIDGE * np.eye(A.shape[1])
    reg[-1, -1] = 0.0                      # do not penalise the intercept
    beta = np.linalg.solve(A.T @ A + reg, A.T @ y[train])

    report = {
        "dataset": "MoleculeNet Lipophilicity (experimental logD 7.4, ChEMBL)",
        "n_molecules": int(len(mols)),
        "n_atom_types": len(types),
        "split": "scaffold (train+valid vs held-out test)",
        "ridge_lambda": RIDGE,
        "train": metrics(y[train], X[train] @ beta),
        "test": metrics(y[test], X[test] @ beta),
        "baseline_predict_mean": metrics(y[test], np.full(len(test), y[train].mean())),
    }

    contributions = {t: float(b) for t, b in zip(types, beta[:-2])}
    out = ROOT / "nexus" / "chem" / "logp_params.py"
    lines = [
        '"""Fitted contributions for the atom-contribution logP model.',
        "",
        "Generated by benchmarks/fit_logp.py -- do not edit by hand.",
        f"Fitted on {report['n_molecules']} compounds with experimental logD 7.4",
        "(MoleculeNet Lipophilicity, sourced from ChEMBL), scaffold split.",
        f"Held-out test MAE {report['test']['mae']:.3f}, R^2 {report['test']['r2']:.3f}.",
        '"""',
        "",
        f"LOGP_INTERCEPT = {float(beta[-1]):.6f}",
        f"LOGP_H = {float(beta[-2]):.6f}",
        "",
        "LOGP_CONTRIBUTIONS: dict[str, float] = {",
    ]
    for t in sorted(contributions):
        lines.append(f'    "{t}": {contributions[t]:.6f},')
    lines.append("}")
    out.write_text("\n".join(lines) + "\n")

    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "logp_fit.json").write_text(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
